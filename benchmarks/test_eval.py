"""Benchmark harness -- accuracy + performance evaluation.

Covers two things:

  1. The harness itself (benchmarks/metrics.py + benchmarks/run_eval.py):
     the ranking metrics compute correct values, and a fresh end-to-end run
     writes a results document with the required metric schema. These run
     against a small synthetic corpus and a temp output path, so the suite
     stays fast and never disturbs the shipped artifact.

  2. The shipped artifact (benchmarks/results.json), regenerated by the
     full `python benchmarks/run_eval.py` at 1k / 10k / 100k and committed
     alongside BENCHMARKS.md: it exists, is non-empty, and carries every
     required metric key at the sizes and for the approaches the report
     compares.

Required per-record metric keys: recall_at_10, ndcg_at_10, latency_p50_ms,
latency_p95_ms, peak_memory_mb -- present both at the top level (the primary
"hybrid" approach at the largest size) and on every per-(size, approach)
record.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

BENCH_DIR = Path(__file__).resolve().parent
REPO_ROOT = BENCH_DIR.parent
RUN_EVAL = BENCH_DIR / "run_eval.py"
COMMITTED_RESULTS = BENCH_DIR / "results.json"

REQUIRED_METRIC_KEYS = (
    "recall_at_10",
    "ndcg_at_10",
    "latency_p50_ms",
    "latency_p95_ms",
    "peak_memory_mb",
)

# Small + fast; the shipped report uses run_eval.REPORT_DATASET_SIZES.
SMOKE_SIZES = (200, 500)
SMOKE_QUERIES = 25
REPORT_DATASET_SIZES = (1_000, 10_000, 100_000)
BASELINE_APPROACHES = {"dense", "sparse", "hybrid"}


def _assert_metric_ranges(record: dict) -> None:
    assert 0.0 <= record["recall_at_10"] <= 1.0
    assert 0.0 <= record["ndcg_at_10"] <= 1.0
    assert record["latency_p50_ms"] > 0.0
    assert record["latency_p95_ms"] >= record["latency_p50_ms"]
    assert record["peak_memory_mb"] > 0.0


# --- metrics.py: pure ranking metrics ----------------------------------


def test_recall_at_k_matches_hand_computed_value():
    from metrics import recall_at_k

    retrieved = ["a", "b", "c", "d", "e", "f"]
    relevant = {"b", "e", "z"}
    assert recall_at_k(retrieved, relevant, k=5) == pytest.approx(2 / 3)
    assert recall_at_k(retrieved, relevant, k=6) == pytest.approx(2 / 3)
    assert recall_at_k(["x", "y"], {"q"}, k=2) == pytest.approx(0.0)


def test_ndcg_at_k_matches_hand_computed_value():
    import math

    from metrics import ndcg_at_k

    # Relevant at ranks 1 and 3: DCG = 1/log2(2) + 1/log2(4) = 1.5;
    # IDCG = 1/log2(2) + 1/log2(3).
    idcg = 1.0 + 1.0 / math.log2(3)
    assert ndcg_at_k(["a", "b", "c", "d"], {"a", "c"}, k=4) == pytest.approx(1.5 / idcg)
    assert ndcg_at_k(["a", "c", "b"], {"a", "c"}, k=3) == pytest.approx(1.0)
    assert ndcg_at_k(["b", "d"], {"a", "c"}, k=2) == pytest.approx(0.0)


def test_mrr_at_k_is_reciprocal_rank_of_first_hit():
    from metrics import mrr_at_k

    assert mrr_at_k(["x", "y", "a", "b"], {"a", "b"}, k=4) == pytest.approx(1 / 3)
    assert mrr_at_k(["a"], {"a"}, k=1) == pytest.approx(1.0)
    assert mrr_at_k(["x", "y"], {"a"}, k=2) == pytest.approx(0.0)
    # a hit past k does not count
    assert mrr_at_k(["x", "y", "a"], {"a"}, k=2) == pytest.approx(0.0)


def test_synthetic_corpus_is_deterministic_and_well_formed():
    from corpus import build_corpus

    first = build_corpus(300, 20, dim=32)
    second = build_corpus(300, 20, dim=32)
    assert [d["text"] for d in first.documents] == [d["text"] for d in second.documents]
    assert len(first.documents) == 300
    assert all(len(v) == 32 for v in first.embeddings)
    # every query's relevant ids are real documents
    doc_ids = {d["id"] for d in first.documents}
    for query in first.queries:
        assert query["relevant_ids"] <= doc_ids
        assert len(query["relevant_ids"]) >= 1


def test_corpus_query_terms_are_selective():
    """Query terms must not each match a large fraction of the corpus,
    otherwise the sparse (BM25) arm scans most of it per query -- an
    artefact of an unrealistically small vocabulary, not real text."""
    from collections import Counter

    from corpus import build_corpus

    corpus = build_corpus(4000, 60, dim=32)
    df = Counter()
    for doc in corpus.documents:
        df.update(set(doc["text"].split()))
    n = len(corpus.documents)

    # No token is near-ubiquitous (real text is Zipfian, not uniform).
    assert max(df.values()) / n < 0.35

    # Every query term is selective: it matches a small slice of the corpus.
    for query in corpus.queries:
        for term in query["text"].split():
            assert df[term] / n < 0.05, f"{term!r} matches {df[term] / n:.0%} of docs"


# --- run_eval.py: fresh end-to-end run against a temp output ----------


@pytest.fixture(scope="module")
def fresh_run(tmp_path_factory) -> dict:
    out_path = tmp_path_factory.mktemp("bench") / "results.json"
    completed = subprocess.run(
        [
            sys.executable,
            str(RUN_EVAL),
            "--sizes",
            *[str(n) for n in SMOKE_SIZES],
            "--queries",
            str(SMOKE_QUERIES),
            "--no-native",
            "--output",
            str(out_path),
        ],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    assert completed.returncode == 0, f"run_eval.py failed:\nstdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
    assert out_path.exists() and out_path.stat().st_size > 0
    return json.loads(out_path.read_text(encoding="utf-8"))


def test_fresh_run_top_level_has_required_metric_keys(fresh_run):
    for key in REQUIRED_METRIC_KEYS:
        assert key in fresh_run, f"top-level results missing {key!r}"
    _assert_metric_ranges(fresh_run)


def test_fresh_run_every_record_has_required_metric_keys(fresh_run):
    records = fresh_run.get("results")
    assert isinstance(records, list) and records
    for record in records:
        assert "dataset_size" in record and "approach" in record
        for key in REQUIRED_METRIC_KEYS:
            assert key in record, f"{record.get('approach')}@{record.get('dataset_size')} missing {key!r}"
        _assert_metric_ranges(record)


def test_fresh_run_covers_requested_sizes_and_baselines(fresh_run):
    records = fresh_run["results"]
    assert {r["dataset_size"] for r in records} == set(SMOKE_SIZES)
    assert {r["approach"] for r in records} >= BASELINE_APPROACHES


def test_fresh_run_hybrid_not_worse_than_dense(fresh_run):
    by_key = {(r["approach"], r["dataset_size"]): r for r in fresh_run["results"]}
    for size in SMOKE_SIZES:
        hybrid = by_key[("hybrid", size)]["ndcg_at_10"]
        dense = by_key[("dense", size)]["ndcg_at_10"]
        assert hybrid >= dense - 1e-9, f"hybrid nDCG {hybrid} < dense {dense} at size {size}"


def test_report_dataset_sizes_constant_is_exposed():
    import run_eval

    assert tuple(run_eval.REPORT_DATASET_SIZES) == REPORT_DATASET_SIZES


# --- benchmarks/results.json: the committed report artifact ----------


@pytest.fixture(scope="module")
def committed_results() -> dict:
    assert COMMITTED_RESULTS.exists(), (
        "benchmarks/results.json is missing -- regenerate it with `.venv/bin/python benchmarks/run_eval.py`."
    )
    assert COMMITTED_RESULTS.stat().st_size > 0, "benchmarks/results.json is empty"
    return json.loads(COMMITTED_RESULTS.read_text(encoding="utf-8"))


def test_committed_results_top_level_metric_keys(committed_results):
    for key in REQUIRED_METRIC_KEYS:
        assert key in committed_results, f"results.json missing top-level {key!r}"
    _assert_metric_ranges(committed_results)


def test_committed_results_cover_report_sizes_and_approaches(committed_results):
    records = committed_results["results"]
    assert {r["dataset_size"] for r in records} == set(REPORT_DATASET_SIZES), (
        "the committed results.json must be the full 1k/10k/100k run"
    )
    assert {r["approach"] for r in records} >= BASELINE_APPROACHES
    for record in records:
        for key in REQUIRED_METRIC_KEYS:
            assert key in record, f"{record['approach']}@{record['dataset_size']} missing {key!r}"
        _assert_metric_ranges(record)


def test_committed_results_hybrid_beats_dense_recall_at_scale(committed_results):
    """The headline: at the largest reported size, hybrid's Recall@10 is at
    least dense-only's (hybrid should never lose recall by adding BM25)."""
    largest = max(REPORT_DATASET_SIZES)
    by_key = {(r["approach"], r["dataset_size"]): r for r in committed_results["results"]}
    assert by_key[("hybrid", largest)]["recall_at_10"] >= by_key[("dense", largest)]["recall_at_10"]
